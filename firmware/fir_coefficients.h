/**
 * @brief Applies 128-tap FIR filter convolution on a buffer of samples.
 */
static inline void apply_fir_filter(const float* restrict coeffs, const float* restrict state_buf, float* restrict output, int num_samples) {
    for (int n = 0; n < num_samples; n++) {
        float acc = 0.0f;
        for (int k = 0; k < FIR_FILTER_TAPS; k++) {
            acc += coeffs[k] * state_buf[n - k];
        }
        output[n] = acc;
    }
}

